function getInitials(name) {
  if (!name) return 'U';
  const parts = name.trim().split(/\s+/);
  if (parts.length === 1) return parts[0].slice(0, 2).toUpperCase();
  return (parts[0][0] + parts[parts.length - 1][0]).toUpperCase();
}

// Toast notification helper with clean SVG icons
function showToast(message, type = 'info') {
  let container = document.getElementById('toast-container');
  if (!container) {
    container = document.createElement('div');
    container.id = 'toast-container';
    container.className = 'toast-container';
    document.body.appendChild(container);
  }

  const toast = document.createElement('div');
  toast.className = `toast toast-${type}`;
  
  let iconSvg = ICONS.info;
  if (type === 'success') iconSvg = ICONS.check;
  if (type === 'error') iconSvg = ICONS.alert;
  if (type === 'copy') iconSvg = ICONS.copy;

  toast.innerHTML = `<span class="toast-icon">${iconSvg}</span><span class="toast-msg">${message}</span>`;
  container.appendChild(toast);

  setTimeout(() => {
    toast.style.opacity = '0';
    toast.style.transform = 'translateY(10px)';
    toast.style.transition = 'all 0.25s ease';
    setTimeout(() => toast.remove(), 250);
  }, 3200);
}

// Lightbox full-size image viewer
function openLightbox(imageUrl, caption = '') {
  const lightbox = document.getElementById('lightbox-modal');
  const img = document.getElementById('lightbox-img');
  const cap = document.getElementById('lightbox-caption');
  
  img.src = imageUrl;
  cap.textContent = caption || 'Anime Visual Frame Preview';
  lightbox.classList.add('active');
}

function closeLightbox() {
  const lightbox = document.getElementById('lightbox-modal');
  lightbox.classList.remove('active');
}

// Modal open/close helpers
function openModal(modalId) {
  const m = document.getElementById(modalId);
  if (m) m.classList.add('active');
}

function closeModal(modalId) {
  const m = document.getElementById(modalId);
  if (m) m.classList.remove('active');
}

// Copy prompt to clipboard
async function copyToClipboard(text, label = 'Prompt') {
  try {
    await navigator.clipboard.writeText(text);
    showToast(`${label} copied to clipboard!`, 'copy');
  } catch (err) {
    const ta = document.createElement('textarea');
    ta.value = text;
    document.body.appendChild(ta);
    ta.select();
    document.execCommand('copy');
    document.body.removeChild(ta);
    showToast(`${label} copied to clipboard!`, 'copy');
  }
}

// Setup upload dropzone drag & drop events
function setupDropzone(dropzoneEl, inputEl, previewGridEl) {
  let selectedFiles = [];

  dropzoneEl.addEventListener('click', () => inputEl.click());

  ['dragenter', 'dragover'].forEach(name => {
    dropzoneEl.addEventListener(name, (e) => {
      e.preventDefault();
      dropzoneEl.classList.add('dragover');
    });
  });

  ['dragleave', 'drop'].forEach(name => {
    dropzoneEl.addEventListener(name, (e) => {
      e.preventDefault();
      dropzoneEl.classList.remove('dragover');
    });
  });

  dropzoneEl.addEventListener('drop', (e) => {
    if (e.dataTransfer.files && e.dataTransfer.files.length > 0) {
      handleFiles(e.dataTransfer.files);
    }
  });

  inputEl.addEventListener('change', (e) => {
    if (e.target.files && e.target.files.length > 0) {
      handleFiles(e.target.files);
    }
  });

  function handleFiles(files) {
    for (let i = 0; i < files.length; i++) {
      selectedFiles.push(files[i]);
    }
    renderPreviews();
  }

  function renderPreviews() {
    previewGridEl.innerHTML = '';
    selectedFiles.forEach((file, index) => {
      const card = document.createElement('div');
      card.className = 'preview-thumb-card';
      const img = document.createElement('img');
      img.src = URL.createObjectURL(file);
      
      const removeBtn = document.createElement('button');
      removeBtn.className = 'remove-thumb-btn';
      removeBtn.innerHTML = ICONS.close;
      removeBtn.type = 'button';
      removeBtn.onclick = (e) => {
        e.stopPropagation();
        selectedFiles.splice(index, 1);
        renderPreviews();
      };

      card.appendChild(img);
      card.appendChild(removeBtn);
      previewGridEl.appendChild(card);
    });
  }

  return {
    getFiles: () => selectedFiles,
    clearFiles: () => {
      selectedFiles = [];
      previewGridEl.innerHTML = '';
      inputEl.value = '';
    }
  };
}
